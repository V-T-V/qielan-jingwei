def to_wgs(x, y):
    import math
    lat = ANCHOR["lat0"] + y / 111320.0
    lng = ANCHOR["lng0"] + x / (111320.0 * math.cos(math.radians(ANCHOR["lat0"])))
    return round(lat, 6), round(lng, 6)

